import AppKit
import Combine

@MainActor
final class ClipboardMonitor: NSObject, ObservableObject {
    @Published private(set) var hasStarted: Bool
    @Published private(set) var isPaused = false
    @Published private(set) var accessIssue: String?
    @Published private(set) var copyIssue: String?

    private let store: HistoryStore
    private let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private var lastChange: Int
    private var timer: Timer?

    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = Set([
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"
    ].map { NSPasteboard.PasteboardType($0) })

    init(store: HistoryStore, pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard) {
        self.store = store
        self.pasteboard = pasteboard
        self.defaults = defaults
        lastChange = pasteboard.changeCount
        hasStarted = defaults.bool(forKey: "hasStarted")
        isPaused = defaults.bool(forKey: "isPaused")
        super.init()
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.6, target: self, selector: #selector(tick), userInfo: nil, repeats: true)
        timer.tolerance = 0.15
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func enable() {
        lastChange = pasteboard.changeCount
        hasStarted = true
        isPaused = false
        defaults.set(true, forKey: "hasStarted")
        defaults.set(false, forKey: "isPaused")
    }

    func togglePause() {
        lastChange = pasteboard.changeCount
        isPaused.toggle()
        defaults.set(isPaused, forKey: "isPaused")
    }

    @objc private func tick() { poll() }

    func poll(userInitiated: Bool = false) {
        guard hasStarted, !isPaused else {
            lastChange = pasteboard.changeCount
            return
        }
        if #available(macOS 15.4, *) {
            let behavior = pasteboard.accessBehavior
            if behavior == .alwaysDeny || (behavior == .ask && !userInitiated) {
                let issue = String(localized: "Allow ClipNest in System Settings → Privacy & Security → Paste from Other Apps for background history.")
                if accessIssue != issue { accessIssue = issue }
                return
            }
            if accessIssue != nil { accessIssue = nil }
        }
        guard userInitiated || pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard Self.ignoredTypes.isDisjoint(with: pasteboard.types ?? []) else { return }
        guard let text = pasteboard.string(forType: .string) ?? pasteboard.string(forType: .URL) else { return }
        // A promised pasteboard value may change while another application supplies it.
        guard pasteboard.changeCount == lastChange else { return }
        store.add(text)
    }

    @discardableResult
    func copy(_ entry: HistoryEntry) -> Bool {
        pasteboard.clearContents()
        let succeeded = pasteboard.setString(entry.text, forType: .string)
        lastChange = pasteboard.changeCount
        copyIssue = succeeded ? nil : String(localized: "Could not copy this entry. Please try again.")
        return succeeded
    }

    func clearHistory() {
        lastChange = pasteboard.changeCount
        store.clear()
    }
}
